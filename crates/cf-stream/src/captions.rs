//! Captions and subtitles: WebVTT uploads and AI-generated captions.

use bytes::Bytes;
use reqwest::Method;
use reqwest::multipart::{Form, Part};
use serde::{Deserialize, Serialize};

use crate::client::Client;
use crate::error::Result;
use crate::transport::ApiRequest;
use crate::types::VideoId;

/// Caption endpoints. Created by [`Client::captions`].
///
/// Languages are BCP 47 tags such as `en` or `pt-BR`.
#[derive(Clone, Copy, Debug)]
#[non_exhaustive]
pub struct Captions<'a> {
    client: &'a Client,
}

/// A caption or subtitle track of a video.
#[derive(Clone, Debug, PartialEq, Eq, Deserialize, Serialize)]
#[non_exhaustive]
pub struct Caption {
    /// The language tag (BCP 47).
    pub language: Option<String>,
    /// The language's name in that language, e.g. `Español`.
    pub label: Option<String>,
    /// `true` if the track was generated by AI.
    pub generated: Option<bool>,
    /// Generation status; absent for uploaded tracks.
    pub status: Option<CaptionStatus>,
}

/// Status of a generated caption track.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
#[non_exhaustive]
pub enum CaptionStatus {
    /// Available.
    Ready,
    /// Still being generated.
    #[serde(rename = "inprogress")]
    InProgress,
    /// Generation failed.
    Error,
    /// A value this version of the crate doesn't recognize.
    #[serde(other, skip_serializing)]
    Unknown,
}

impl<'a> Captions<'a> {
    pub(crate) fn new(client: &'a Client) -> Self {
        Self { client }
    }

    /// Lists a video's caption tracks, including generated tracks that are
    /// still in progress or failed.
    ///
    /// `GET /accounts/{account_id}/stream/{video_id}/captions`
    ///
    /// ```no_run
    /// # async fn run(client: cf_stream::Client) -> cf_stream::Result<()> {
    /// let captions = client.captions().list(&"ea95132c15732412d22c1476fa83f27a".into()).await?;
    /// # Ok(()) }
    /// ```
    pub async fn list(&self, video: &VideoId) -> Result<Vec<Caption>> {
        let request = ApiRequest::get([video.as_str(), "captions"]);
        let list: Option<Vec<Caption>> = self.client.inner.json(request).await?;
        Ok(list.unwrap_or_default())
    }

    /// Fetches one caption track.
    ///
    /// `GET /accounts/{account_id}/stream/{video_id}/captions/{language}`
    ///
    /// ```no_run
    /// # async fn run(client: cf_stream::Client) -> cf_stream::Result<()> {
    /// let caption = client.captions().get(&"ea95132c15732412d22c1476fa83f27a".into(), "en").await?;
    /// # Ok(()) }
    /// ```
    pub async fn get(&self, video: &VideoId, language: &str) -> Result<Caption> {
        let request = ApiRequest::get([video.as_str(), "captions", language]);
        self.client.inner.json(request).await
    }

    /// Uploads a WebVTT file (at most 10 MB) for a language, replacing any
    /// existing track for it.
    ///
    /// `PUT /accounts/{account_id}/stream/{video_id}/captions/{language}`
    /// (multipart/form-data)
    ///
    /// ```no_run
    /// # async fn run(client: cf_stream::Client) -> cf_stream::Result<()> {
    /// let vtt = std::fs::read("captions.en.vtt").expect("read file");
    /// let caption = client
    ///     .captions()
    ///     .upload(&"ea95132c15732412d22c1476fa83f27a".into(), "en", vtt)
    ///     .await?;
    /// # Ok(()) }
    /// ```
    pub async fn upload(
        &self,
        video: &VideoId,
        language: &str,
        vtt: impl Into<Bytes>,
    ) -> Result<Caption> {
        let vtt: Bytes = vtt.into();
        let len = vtt.len() as u64;
        let part = Part::stream_with_length(vtt, len)
            .file_name(format!("{language}.vtt"))
            .mime_str("text/vtt")?;
        let form = Form::new().part("file", part);
        let request =
            ApiRequest::new(Method::PUT, [video.as_str(), "captions", language]).multipart(form);
        self.client.inner.json(request).await
    }

    /// Starts generating captions for a language with AI. The video must be
    /// ready, and any existing track for the language must be deleted
    /// first. Poll [`get`](Self::get) until the status is `Ready`.
    ///
    /// `POST /accounts/{account_id}/stream/{video_id}/captions/{language}/generate`
    ///
    /// ```no_run
    /// # async fn run(client: cf_stream::Client) -> cf_stream::Result<()> {
    /// let caption = client
    ///     .captions()
    ///     .generate(&"ea95132c15732412d22c1476fa83f27a".into(), "en")
    ///     .await?;
    /// # Ok(()) }
    /// ```
    pub async fn generate(&self, video: &VideoId, language: &str) -> Result<Caption> {
        let request = ApiRequest::new(
            Method::POST,
            [video.as_str(), "captions", language, "generate"],
        );
        self.client.inner.json(request).await
    }

    /// Deletes a caption track.
    ///
    /// `DELETE /accounts/{account_id}/stream/{video_id}/captions/{language}`
    ///
    /// ```no_run
    /// # async fn run(client: cf_stream::Client) -> cf_stream::Result<()> {
    /// client.captions().delete(&"ea95132c15732412d22c1476fa83f27a".into(), "en").await?;
    /// # Ok(()) }
    /// ```
    pub async fn delete(&self, video: &VideoId, language: &str) -> Result<()> {
        let request = ApiRequest::new(Method::DELETE, [video.as_str(), "captions", language]);
        self.client.inner.empty(request).await
    }

    /// Downloads a caption track as WebVTT text.
    ///
    /// `GET /accounts/{account_id}/stream/{video_id}/captions/{language}/vtt`
    ///
    /// ```no_run
    /// # async fn run(client: cf_stream::Client) -> cf_stream::Result<()> {
    /// let vtt = client.captions().vtt(&"ea95132c15732412d22c1476fa83f27a".into(), "en").await?;
    /// assert!(vtt.starts_with("WEBVTT"));
    /// # Ok(()) }
    /// ```
    pub async fn vtt(&self, video: &VideoId, language: &str) -> Result<String> {
        let request = ApiRequest::get([video.as_str(), "captions", language, "vtt"]);
        self.client.inner.text(request).await
    }
}
